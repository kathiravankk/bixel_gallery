  /// Filter & paginate curated images
  static PixabayResponseModel getCuratedResponse({
    String query = '',
    String category = '',
    int page = 1,
    int perPage = 20,
  }) {
    List<PixabayImageModel> filtered = List.from(_allCuratedImages);

    // Apply category filter
    if (category.isNotEmpty && category.toLowerCase() != 'all') {
      filtered = filtered.where((item) {
        return item.tags.toLowerCase().contains(category.toLowerCase());
      }).toList();
    }

    // Apply query filter
    if (query.isNotEmpty) {
      final q = query.toLowerCase().trim();
      filtered = filtered.where((item) {
        return item.tags.toLowerCase().contains(q) ||
            item.user.toLowerCase().contains(q);
      }).toList();
    }

    // Simulate multi-page expansion for infinite scroll testing
    List<PixabayImageModel> pool = [];
    for (int i = 0; i < 5; i++) {
      for (var item in filtered) {
        // synthesize unique IDs for subsequent pages
        pool.add(
          PixabayImageModel(
            id: item.id + (i * 1000),
            pageURL: item.pageURL,
            type: item.type,
            tags: item.tags,
            previewURL: item.previewURL,
            previewWidth: item.previewWidth,
            previewHeight: item.previewHeight,
            webformatURL: item.webformatURL,
            webformatWidth: item.webformatWidth,
            webformatHeight: item.webformatHeight,
            largeImageURL: item.largeImageURL,
            imageWidth: item.imageWidth,
            imageHeight: item.imageHeight,
            imageSize: item.imageSize,
            views: item.views + (i * 120),
            downloads: item.downloads + (i * 45),
            likes: item.likes + (i * 12),
            comments: item.comments,
            userId: item.userId,
            user: item.user,
            userImageURL: item.userImageURL,
          ),
        );
      }
    }

    int startIndex = (page - 1) * perPage;
    if (startIndex >= pool.length) {
      return PixabayResponseModel(
        total: pool.length,
        totalHits: pool.length,
        hits: [],
      );
    }

    int endIndex = (startIndex + perPage).clamp(0, pool.length);
    List<PixabayImageModel> pageItems = pool.sublist(startIndex, endIndex);

    return PixabayResponseModel(
      total: pool.length,
      totalHits: pool.length,
      hits: pageItems,
    );
  }
